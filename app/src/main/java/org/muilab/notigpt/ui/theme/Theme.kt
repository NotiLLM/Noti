/**
 * Convenience accessors mirroring [MaterialTheme]. Use `NotiTheme.semantic.taskAccent` etc.
 */
object NotiTheme {
    val semantic: NotiSemanticColors
        @Composable @ReadOnlyComposable get() = LocalNotiColors.current
}

/**
 * Compose Material theme configuration for NotiGPT.
 *
 * The custom neutral scheme is the default. Dynamic color (Material You) is opt-in via
 * [SharedPreferencesManager.useDynamicColor] and only retints the neutral chrome — the [NotiSemanticColors]
 * provided here are always fixed so section/urgency meaning never shifts with the wallpaper.
 */
@Composable
fun NotiTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = SharedPreferencesManager.useDynamicColor,
    content: @Composable () -> Unit,
) {
    val colorScheme: ColorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }

    val notiColors = if (darkTheme) DarkNotiColors else LightNotiColors

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            window.statusBarColor = colorScheme.surface.toArgb()
            WindowCompat.getInsetsController(window, view).isAppearanceLightStatusBars = !darkTheme
        }
    }

    CompositionLocalProvider(LocalNotiColors provides notiColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            content = content,
        )
    }
}
